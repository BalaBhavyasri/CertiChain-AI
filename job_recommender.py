# RECOMMEND JOBS
# =========================================================

def recommend_jobs(candidate_skills, program=None):

    recommended = []

    candidate_skills_lower = [
        skill.lower()
        for skill in candidate_skills
    ]

    program_profile = get_program_profile(program)

    # If no skills detected at all, provide general recommendations
    if not candidate_skills_lower:
        return ["Backend Developer", "Frontend Developer", "Full Stack Developer"]

    for role, details in career_database.items():

        required_skills = [
            skill.lower()
            for skill in details["skills"]
        ]

        matched = 0

        for skill in candidate_skills_lower:
            if skill in required_skills:
                matched += 1

        match_percentage = (matched / len(required_skills)) * 100 if required_skills else 0

        if program_profile:
            if role in program_profile["roles"] and match_percentage >= 20:
                recommended.append((role, match_percentage + 10))
            elif match_percentage >= 55:
                recommended.append((role, match_percentage))
            elif role in program_profile["roles"] and match_percentage >= 10:
                recommended.append((role, match_percentage + 5))
        else:
            if match_percentage >= 40:
                recommended.append((role, match_percentage))
            elif match_percentage >= 25:
                recommended.append((role, match_percentage - 5))

    if program_profile and not recommended:
        for role_name in program_profile["roles"]:
            recommended.append((role_name, 15))

    # If no recommendations found, provide defaults based on most common skills
    if not recommended:
        return ["Full Stack Developer", "Backend Developer", "Frontend Developer"]
    
    # Sort by match percentage and return just the role names
    recommended.sort(key=lambda x: x[1], reverse=True)
    return [role for role, _ in recommended]

# =========================================================
# JOB FIT SCORE
# =========================================================

def calculate_job_fit(candidate_skills, job_role):

    candidate_skills_lower = [
        skill.lower()
        for skill in candidate_skills
    ]

    role_profile = get_role_profile(job_role)
    required_skills = [
        skill.lower()
        for skill in role_profile["skills"]
    ]

    matched = 0

    for skill in candidate_skills_lower:
        if skill in required_skills:
            matched += 1

    if len(required_skills) == 0:
        return 0

    fit_score = (matched / len(required_skills)) * 100
    return round(fit_score, 2)

# =========================================================
# SKILL GAP ANALYSIS
# =========================================================

def skill_gap_analysis(candidate_skills, job_role):

    candidate_skills_lower = [
        skill.lower()
        for skill in candidate_skills
    ]

    role_profile = get_role_profile(job_role)
    required_skills = [
        skill.lower()
        for skill in role_profile["skills"]
    ]

    missing = []

    for skill in required_skills:
        if skill not in candidate_skills_lower:
            missing.append(skill)

    return missing

# =========================================================
# GENERATE LEARNING PATH
# =========================================================

def generate_learning_path(job_role):

    role_profile = get_role_profile(job_role)
    return role_profile["roadmap"]

# =========================================================
# COMPLETE CAREER ANALYSIS
# =========================================================

def analyze_candidate(candidate_skills, program=None):

    recommendations = []

    jobs = recommend_jobs(candidate_skills, program)

    for job in jobs:

        fit_score = calculate_job_fit(

            candidate_skills,
            job
        )

        missing_skills = skill_gap_analysis(

            candidate_skills,
            job
        )

        roadmap = generate_learning_path(job)

        recommendations.append({

            "job_role": job,

            "fit_score": fit_score,

            "missing_skills": missing_skills,

            "roadmap": roadmap
        })

    recommendations.sort(

        key=lambda x: x["fit_score"],

        reverse=True
    )

    return recommendations
